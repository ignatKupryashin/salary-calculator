export interface IncomeTaxRate {
    /**
     * Доход, до достижения которого применяется указанная ставка <br>
     * null используется для указания бесконечности
     */
    income: number | null;
    /**
     * Ставка налога. Указывается в десятичной дроби. Например, 13% указывается как 0.13
     */
    rate: number;
}